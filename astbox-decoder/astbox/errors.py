class AstboxError(Exception):
    """ASTBOX error carrying the canonical UINT16 code and a message."""

    def __init__(self, code, message):
        self.code = code
        self.message = message
        super().__init__("ASTBOX_E_%04X: %s" % (code, message))

    @property
    def code_name(self):
        for name, value in list(globals().items()):
            if name.startswith("E_") and value == self.code:
                return "ASTBOX_" + name
        return "ASTBOX_E_%04X" % self.code
